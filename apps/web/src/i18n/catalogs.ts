export const catalogs: Readonly<Record<Locale, Readonly<Record<MessageKey, string>>>> = { en, 'ar-EG': ar };

export const directionForLocale = (locale: Locale): 'ltr' | 'rtl' => (locale === 'ar-EG' ? 'rtl' : 'ltr');
export const isLocale = (value: unknown): value is Locale => supportedLocales.includes(value as Locale);

export const translate = (locale: Locale, key: MessageKey, values: Readonly<Record<string, string | number>> = {}): string =>
  Object.entries(values).reduce((message, [name, value]) => message.replaceAll(`{${name}}`, String(value)), catalogs[locale][key]);
